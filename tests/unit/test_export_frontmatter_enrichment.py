"""Export claude-plugin frontmatter enrichment tests.

The plugin.json generated by `olav export claude-plugin` must include agent
metadata parsed from AGENT.md YAML frontmatter:
    - name → plugin.name (overrides the default "olav-{agent}-plugin")
    - description → plugin.description
    - subagents → plugin.subagents

The agents/{agent}.md file is a *Claude-specific* rewrite of the AGENT.md:
    - YAML frontmatter must use Claude keys (name, description, tools)
    - The original OLAV-specific fields (system_prompt_file, static_context)
      must be stripped from the exported frontmatter.
"""

import textwrap
from pathlib import Path


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _write_agent_md(agent_dir: Path, name: str, description: str, subagents: list) -> None:
    if subagents:
        subagents_block = "\n" + "\n".join(f"  - {s}" for s in subagents)
    else:
        subagents_block = " []"
    lines = [
        "---",
        f"name: {name}",
        f'description: "{description}"',
        "system_prompt_file: prompts/system.md",
        f"subagents:{subagents_block}",
        "static_context:",
        "  - path: ./references/REF.md",
        "---",
        "",
        "## Overview",
        "",
        "Agent body content.",
    ]
    content = "\n".join(lines) + "\n"
    agent_dir.mkdir(parents=True, exist_ok=True)
    (agent_dir / "AGENT.md").write_text(content, encoding="utf-8")
    (agent_dir / "SKILL.md").write_text("# Skills\n", encoding="utf-8")


def _run_export(agent_name: str, workspace: Path, output: Path) -> str:
    import asyncio
    from olav.cli.commands.export import ExportCommand

    cmd = ExportCommand()
    cmd.workspace_root = workspace
    return asyncio.run(cmd.execute(f"claude-plugin --agent {agent_name} --output {output}"))


# ---------------------------------------------------------------------------
# plugin.json enrichment
# ---------------------------------------------------------------------------

def test_plugin_json_includes_agent_name_from_frontmatter(tmp_path: Path) -> None:
    import json
    workspace = tmp_path / "workspace"
    _write_agent_md(workspace / "quick", "quick-orchestrator", "Fast SQL queries", [])
    _run_export("quick", workspace, tmp_path / "dist")

    plugin = json.loads((tmp_path / "dist" / ".claude-plugin" / "plugin.json").read_text())
    assert plugin["name"] == "quick-orchestrator", (
        f"plugin.name should come from AGENT.md frontmatter, got: {plugin['name']!r}"
    )


def test_plugin_json_includes_description_from_frontmatter(tmp_path: Path) -> None:
    import json
    workspace = tmp_path / "workspace"
    _write_agent_md(workspace / "ops", "ops-orchestrator", "Deep troubleshooting agent", [])
    _run_export("ops", workspace, tmp_path / "dist")

    plugin = json.loads((tmp_path / "dist" / ".claude-plugin" / "plugin.json").read_text())
    assert plugin.get("description") == "Deep troubleshooting agent"


def test_plugin_json_includes_subagents_from_frontmatter(tmp_path: Path) -> None:
    import json
    workspace = tmp_path / "workspace"
    _write_agent_md(workspace / "sync", "sync-orchestrator", "Sync agent", ["ops", "quick"])
    _run_export("sync", workspace, tmp_path / "dist")

    plugin = json.loads((tmp_path / "dist" / ".claude-plugin" / "plugin.json").read_text())
    assert "subagents" in plugin
    assert "ops" in plugin["subagents"]
    assert "quick" in plugin["subagents"]


# ---------------------------------------------------------------------------
# Exported agents/{agent}.md — Claude-compatible frontmatter
# ---------------------------------------------------------------------------

def test_exported_agent_md_has_claude_frontmatter(tmp_path: Path) -> None:
    """Exported AGENT.md must have YAML frontmatter with name and description."""
    workspace = tmp_path / "workspace"
    _write_agent_md(workspace / "audit", "audit-orchestrator", "Audit checks", [])
    _run_export("audit", workspace, tmp_path / "dist")

    exported_md = (tmp_path / "dist" / "agents" / "audit.md").read_text()
    assert exported_md.startswith("---"), "exported AGENT.md must have YAML frontmatter"
    assert "name:" in exported_md
    assert "description:" in exported_md


def test_exported_agent_md_strips_olav_specific_keys(tmp_path: Path) -> None:
    """Exported AGENT.md must not contain OLAV-specific keys."""
    workspace = tmp_path / "workspace"
    _write_agent_md(workspace / "config", "config-orchestrator", "Config discovery", [])
    _run_export("config", workspace, tmp_path / "dist")

    exported_md = (tmp_path / "dist" / "agents" / "config.md").read_text()
    assert "system_prompt_file:" not in exported_md, (
        "system_prompt_file is an OLAV-specific key and should be stripped from Claude export"
    )
    assert "static_context:" not in exported_md, (
        "static_context is an OLAV-specific key and should be stripped"
    )

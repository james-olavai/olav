class TestSchemaReferenceDomainMapping:
    """OC-8 intent: "document the protocol-domain mapping" (openconfig-bgp etc.).

    R83 re-spec: protocol domains map to canonical sources; the
    reference must name them AND fence off hallucinated alternatives.
    """


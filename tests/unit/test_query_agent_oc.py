"""SCHEMA_REFERENCE.md contract tests — R83 data-access model.

History: this file was born as OC-8 ("SCHEMA_REFERENCE.md must document
OpenConfig JSON path query patterns"). R82 rewrote the reference around
the four canonical sources and R83 replaced OpenConfig JSON-path
querying with per-command zero-ETL auto-views; the OC-8 assertions went
strict-xfail on 2026-06-12 and were re-specified against the R83 model
on 2026-06-13. Each test below maps one original OC-8 intent onto its
R83 equivalent (noted per test).

The tests read the TRACKED bundle copy (src/olav/data/workspace) so
they work on a fresh checkout without `olav init`; the workspace drift
gate (tests/governance/test_workspace_drift_gate.py) guarantees the
runtime copy is byte-identical.
"""

from pathlib import Path

_REPO = Path(__file__).resolve().parents[2]
_REF = _REPO / "src" / "olav" / "data" / "workspace" / "core" / "references" / "SCHEMA_REFERENCE.md"


def _content() -> str:
    return _REF.read_text(encoding="utf-8")


class TestSchemaReferenceAutoViewModel:
    """OC-8 intent: "document the data-access model for parsed device state."

    R83 re-spec: the model is the two-layer auto-view architecture, not
    OpenConfig JSON paths — the reference must document both layers.
    """

    def test_reference_documents_semantic_views_layer(self):
        """Layer 1: cross-vendor semantic views for BGP / OSPF / L2."""
        content = _content()
        for view in (
            "v_bgp_neighbors_auto",
            "v_ospf_neighbors_auto",
            "v_l2_links_auto",
        ):
            assert view in content, f"SCHEMA_REFERENCE.md must document {view}"

    def test_reference_documents_per_command_autoview_layer(self):
        """Layer 2: per-command zero-ETL views generated by /netops_init."""
        content = _content()
        assert "v_%_auto" in content, (
            "Must document the auto-view discovery pattern "
            "(information_schema.views ... LIKE 'v_%_auto')"
        )
        assert "unnest" in content.lower() or "zero-etl" in content.lower(), (
            "Must explain that auto-views are DuckDB-native unnest/zero-ETL views"
        )
        assert "DESCRIBE" in content, (
            "Must teach DESCRIBE <view> as the column-discovery step"
        )



🎯 核心概念
──────────────────────────────────────────────────────────────────────────────

   完全重新索引 (旧方式)              增量/差量更新 (新方式)
   ├─ 重读所有 PDF/Markdown         ├─ 仅读改动文件
   ├─ 重新分割所有 chunks           ├─ 跳过未改文件
   ├─ 重新生成所有 embeddings       ├─ 仅对改动生成向量
   ├─ 时间: 5-10 分钟               ├─ 时间: 30 秒 - 2 分钟
   └─ 浪费: 大量重复计算             └─ 高效: 按需处理

   差异对比: 无改动时 412倍加速 ⚡

════════════════════════════════════════════════════════════════════════════════

💾 如何工作？
──────────────────────────────────────────────────────────────────────────────

   Step 1. 计算文件 SHA256 哈希
           ↓
   Step 2. 查询 indexed_files 表中的存储哈希
           ↓
   Step 3. 比较哈希值
           ├─ 相同 → ✓ SKIP (跳过)
           ├─ 不同 → ↻ 删除旧chunks，重新索引
           └─ 不存在 → ✨ 新文件，直接索引
           ↓
   Step 4. 更新 indexed_files 记录


_TOOL_TEMPLATE = '''\
"""Auto-generated tool: {display_name} — {group_description}

Generated by olav.platform.services.tool_generator
Service: {service_name}
Tag group: {tag}
DO NOT EDIT MANUALLY — re-run `olav service register {service_name}` to update.
"""

from __future__ import annotations

from langchain_core.tools import tool

from olav.platform.services.client import service_call as _call


{tool_functions}
'''

_FUNCTION_TEMPLATE = '''\
@tool
def {func_name}({params}) -> dict:
    """{summary}

    Service: {service_name}  |  {method} {path}
    {write_note}"""
    return _call(
        "{service_name}",
        "{method}",
        f"{path_template}",{body_arg}{response_def_arg}{confirmed_arg}
    )
'''


# ---------------------------------------------------------------------------
# Name helpers
# ---------------------------------------------------------------------------

def _to_func_name(prefix: str, method: str, path: str) -> str:
    """Build a Python function name from a tool prefix + HTTP method + path.

    Example: ("clab", "GET", "/api/v1/labs/{name}") → "clab_get_labs_by_name"
    """
    # Strip leading /api/v1/ prefixes
    slug = re.sub(r"^(/api/v\d+)?/", "", path).strip("/")
    # Replace path params {name} → by_name
    slug = re.sub(r"\{(\w+)\}", lambda m: f"by_{m.group(1)}", slug)
    # Slugify
    slug = re.sub(r"[^a-z0-9]+", "_", slug.lower()).strip("_")
    return f"{prefix}_{method.lower()}_{slug}" if slug else f"{prefix}_{method.lower()}"


def _path_to_fstring(path: str) -> str:
    """Convert OpenAPI path /labs/{name} to Python f-string body /labs/{name}."""
    return path  # Python f-string syntax matches OpenAPI {} style


def _build_function(
    svc_name: str,
    prefix: str,
    method: str,
    path: str,
    summary: str | None,
    request_body_def: str | None,
    response_200_def: str | None,
) -> str:
    """Render a single tool function string."""
    func_name = _to_func_name(prefix, method, path)

    # Build parameter list
    # Path params → required positional; body → optional kwarg
    path_params = re.findall(r"\{(\w+)\}", path)
    param_parts = list(path_params)  # positional
    if request_body_def and method.upper() in ("POST", "PUT", "PATCH"):
        param_parts.append("body: dict | None = None")
    params = ", ".join(param_parts)

    # Body kwarg for service_call
    is_write = method.upper() in ("POST", "PUT", "PATCH", "DELETE")
    has_body = request_body_def and method.upper() in ("POST", "PUT", "PATCH")
    body_arg = "\n        body=body," if has_body else ""

    # response_def arg
    response_def_arg = f'\n        response_def="{response_200_def}",' if response_200_def else ""

    # Write operations: add confirmed param so agent can re-call after user approval
    if is_write:
        if param_parts:
            param_parts.append("confirmed: bool = False")
        else:
            param_parts = ["confirmed: bool = False"]
        params = ", ".join(param_parts)
        confirmed_arg = "\n        confirmed=confirmed,"
        write_note = "Write op — first call returns requires_approval; re-call with confirmed=True after user confirms."
    else:
        confirmed_arg = ""
        write_note = ""

    return _FUNCTION_TEMPLATE.format(
        func_name=func_name,
        params=params,
        summary=summary or f"{method} {path}",
        service_name=svc_name,
        method=method.upper(),
        path=path,
        path_template=_path_to_fstring(path),
        body_arg=body_arg,
        response_def_arg=response_def_arg,
        confirmed_arg=confirmed_arg,
        write_note=write_note,
    )


